"""Which modules are supported, which are internal, and which are undecided.

The single machine-readable answer: the contract test, the surface
docstrings and the published docs all defer to the tiers listed here.

The three tiers:

``SUPPORTED``
    Will not change without a deprecation path.  Import freely.

``INTERNAL``
    Changes without notice.  A name used from here is a name nobody knows
    is load-bearing; if you need one, ask for it to be promoted.

``UNDECIDED``
    Neither promised nor disowned — usually because the module predates
    the split and its replacement is not finished.  Treat as internal;
    each entry carries the reason it is not yet either.

``test_stability_manifest.py`` asserts every top-level module appears in
exactly one tier, so a new module cannot be born unclassified.
"""

from __future__ import annotations

from typing import Literal

Tier = Literal["supported", "internal", "undecided"]

#: The two contracts, plus the leaf modules both of them depend on.
SUPPORTED: tuple[str, ...] = (
    "zarr_vectors.api",
    "zarr_vectors.building",
    # Leaves with no internal imports of their own: `exceptions` is class
    # definitions, `typing` is TypeAliases, `constants` is strings. Both
    # surfaces raise, annotate and name things with these, so they cannot
    # be internal without making every supported signature internal too.
    "zarr_vectors.constants",
    "zarr_vectors.exceptions",
    "zarr_vectors.typing",
    "zarr_vectors.headers",
)

#: Change without notice.
INTERNAL: tuple[str, ...] = (
    # The three private top-level modules.  Their *names* are supported --
    # ``__api_version__``, ``FEATURES``, ``require_api``, ``stability`` and
    # ``__version__`` are all re-exported from ``zarr_vectors`` and listed
    # in its ``__all__`` -- but the module paths are not: import them from
    # the package, the way the underscore asks you to.  ``_version`` is
    # generated by setuptools-scm at build time and is gitignored.
    "zarr_vectors._api_version",
    "zarr_vectors._stability",
    "zarr_vectors._version",
    # Host/device array plumbing, the install probe and the GPUDirect
    # Storage probe; the install probe's name is re-exported as
    # ``zarr_vectors.runtime_capabilities``.
    "zarr_vectors._xp",
    "zarr_vectors._runtime",
    "zarr_vectors._gds",
    "zarr_vectors.core",
    "zarr_vectors.encoding",
    "zarr_vectors.spatial",
    "zarr_vectors.lazy",
    "zarr_vectors.ops",
    "zarr_vectors.sharding",
    "zarr_vectors.multiresolution",
    "zarr_vectors._engine",
    "zarr_vectors.rechunk",
)

#: Not yet either, with the reason.
UNDECIDED: dict[str, str] = {
    "zarr_vectors.octree_chunks": (
        "Optional octree chunking of a level (to_octree / to_uniform), on the "
        "octree branch: point clouds and undirected graphs only so far, and "
        "its on-disk layout is an extension the spec does not yet carry."
    ),
    "zarr_vectors.types": (
        "The five store-creating writers are promoted into `building` and "
        "are supported there. The readers are superseded by Level.read() / "
        "ReadResult, but cannot be deprecated until the api can carry "
        "per-vertex attributes for every geometry — pointing callers at a "
        "lossy replacement is worse than leaving them here."
    ),
    "zarr_vectors.validate": (
        "Stable in practice and widely used, but its result objects have "
        "never been given a compatibility promise."
    ),
    "zarr_vectors.gpu": (
        "The optional GPU extension (the `[gpu]` extra). Callers reach it "
        "through `device=` and `runtime_capabilities()`, not by importing "
        "it; its own surface stays unpromised until device-side decode and "
        "GPUDirect I/O settle what it has to offer. The exception meant for "
        "direct import is `decode_zstd` (FEATURES: decode-zstd), a checked "
        "zstd decode for bytes a caller fetched to the device itself."
    ),
    "zarr_vectors.composite": (
        "Multi-geometry stores round-trip now — add_geometry allocates its "
        "namespaced per-chunk arrays and its documented example passes — but "
        "the namespacing itself is unreviewed: a composite store's geometries "
        "live at vertices_<type>, which no other reader in the library knows "
        "how to find. Undecided until that layout is either specified or "
        "replaced."
    ),
}

_TIERS: tuple[tuple[str, Tier], ...] = (
    *((m, "supported") for m in SUPPORTED),
    *((m, "internal") for m in INTERNAL),
    *((m, "undecided") for m in UNDECIDED),
)


def _prefix_tier(module: str) -> Tier | None:
    best: tuple[int, Tier] | None = None
    for prefix, tier in _TIERS:
        if module == prefix or module.startswith(prefix + "."):
            if best is None or len(prefix) > best[0]:
                best = (len(prefix), tier)
    return None if best is None else best[1]


def _exists(name: str) -> bool:
    """Whether ``name`` is an importable module or an attribute of one."""
    import importlib
    import importlib.util

    try:
        if importlib.util.find_spec(name) is not None:
            return True
    except (ImportError, ValueError):
        pass
    parent, _, attr = name.rpartition(".")
    if not parent:
        return False
    try:
        return hasattr(importlib.import_module(parent), attr)
    except ImportError:
        return False


def stability(module: str) -> Tier:
    """Which tier ``module`` (or anything under it) is in.

    Args:
        module: A dotted module name, e.g. ``"zarr_vectors.core.arrays"``,
            or a dotted name exported from one, e.g.
            ``"zarr_vectors.api.Dataset"``.

    The package itself and the names it exports are answered too:
    ``"zarr_vectors"`` is supported, a name listed in
    ``zarr_vectors.__all__`` (``zarr_vectors.open``,
    ``zarr_vectors.stability``, ...) is supported, and any other
    top-level name -- the storage-layer re-exports retired from
    ``__all__``, such as ``zarr_vectors.FsGroup`` or
    ``zarr_vectors.rechunk_by_attribute`` -- is internal: importable for
    now, promised by nobody.  Where one of those has a supported
    spelling it is in :mod:`zarr_vectors.building`.

    Raises:
        KeyError: If nothing in the manifest covers it — which means a
            module was added without being classified — or if no such
            module or exported name exists.  A name that does not exist
            is not "supported" just because it sits under a supported
            prefix.
    """
    if module == "zarr_vectors":
        return "supported"
    if not _exists(module):
        raise KeyError(
            f"{module!r} is not in the stability manifest: no module or "
            f"exported name of that name exists."
        )
    parent, _, attr = module.rpartition(".")
    if parent == "zarr_vectors":
        import importlib.util

        is_module = False
        try:
            is_module = importlib.util.find_spec(module) is not None
        except (ImportError, ValueError):
            pass
        if not is_module:
            import zarr_vectors

            return (
                "supported" if attr in getattr(zarr_vectors, "__all__", ())
                else "internal"
            )
    tier = _prefix_tier(module)
    if tier is None:
        raise KeyError(
            f"{module!r} is not in the stability manifest. Add it to "
            f"SUPPORTED, INTERNAL or UNDECIDED in zarr_vectors/_stability.py "
            f"— a module with no tier is a promise nobody made or refused."
        )
    return tier


def is_internal(module: str) -> bool:
    """Whether importing from ``module`` is reaching past a contract."""
    return stability(module) != "supported"
